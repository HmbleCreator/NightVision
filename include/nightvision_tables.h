/**
 * @brief Fast integer square root using binary restoration (strictly O(1) cycles).
 */
static inline uint32_t nightvision_isqrt_u32(uint32_t val) {
    uint32_t res = 0;
    uint32_t bit = 1u << 30;
    while (bit > val) { bit >>= 2; }
    while (bit != 0) {
        if (val >= res + bit) { val -= res + bit; res = (res >> 1) + bit; }
        else { res >>= 1; }
        bit >>= 2;
    }
    return res;
}

